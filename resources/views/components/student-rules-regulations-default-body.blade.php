<p>
    To maintain professionalism, discipline, and productivity in the workplace, all interns are required to strictly observe the following rules throughout the internship period:
</p>

<section class="space-y-1.5">
    <h3 class="font-bold text-gray-900">Use of Mobile Phones</h3>
    <p>
        The use of mobile phones is strictly prohibited during work hours, except during designated breaks or in case of emergencies. A phone deposit box is provided where interns must place their phones before starting work. If the box cannot be located, interns should approach their Supervisor or the Sales Department for assistance.
    </p>
</section>

<section class="space-y-1.5">
    <h3 class="font-bold text-gray-900">Work Schedule and Duty Hours</h3>
    <p>
        Interns are required to strictly follow the assigned work schedule of <strong>eight (8) hours per day</strong>, from Monday to Friday. Proper log-in and log-out using the time-tracking system is mandatory to ensure accurate recording of duty hours.
    </p>
</section>

<section class="space-y-1.5">
    <h3 class="font-bold text-gray-900">Attendance and Absences</h3>
    <p>
        Absences are <strong>only allowed for valid reasons</strong>, specifically:
    </p>
    <ul class="list-disc pl-5 space-y-1">
        <li>School-related activities (with proper documentation), or</li>
        <li>Sickness or illness (with appropriate notice or medical proof when required)</li>
    </ul>
    <p>
        Any absence outside of these conditions will not be permitted and may be subject to disciplinary action.
    </p>
</section>

<section class="space-y-1.5">
    <h3 class="font-bold text-gray-900">Punctuality</h3>
    <p>
        Interns must report on time. Repeated tardiness or failure to comply with the required duty hours may result in penalties or termination.
    </p>
</section>

<section class="space-y-1.5">
    <h3 class="font-bold text-gray-900">Confidentiality</h3>
    <p>
        Interns must maintain strict confidentiality regarding company data, client information, and internal processes at all times.
    </p>
</section>

<section class="space-y-1.5">
    <h3 class="font-bold text-gray-900">Professional Conduct</h3>
    <p>
        Proper workplace behavior, respect, and professionalism must be consistently observed. Interns are encouraged to collaborate with team members and seek guidance when needed.
    </p>
</section>

<section class="space-y-1.5">
    <h3 class="font-bold text-gray-900">Sleeping During Duty Hours</h3>
    <p>
        Sleeping during working hours is strictly prohibited and will result in <strong>immediate termination</strong> of the internship.
    </p>
</section>

<section class="space-y-1.5">
    <h3 class="font-bold text-gray-900">Policy Violations and Termination</h3>
    <p>
        Any violation of the rules stated above may lead to disciplinary action. <strong>Serious offenses or failure to comply with these regulations will result in the automatic termination of the internship (OJT).</strong>
    </p>
</section>
